import assert from 'node:assert/strict'
import { VICI_PRACTICES } from '../../src/simulations/viciPractice.js'
import { encodePcmWav } from '../../src/training/audioClip.js'

export async function runViciBrowser({ page, context, app, sql, responsive, pass, agentPin, errors }) {
  const create = async (scenario,teamId) => {
    await page.goto(app+'/studio/simulations/create')
    assert.equal(await page.getByText('Positions · optional',{exact:true}).count(),0)
    await page.getByLabel('Title',{exact:true}).fill(VICI_PRACTICES[scenario].title)
    await page.getByLabel('Dialer practice',{exact:true}).check()
    await page.getByLabel('Audience',{exact:true}).selectOption('team')
    await page.getByLabel('Team',{exact:true}).selectOption(teamId)
    await page.getByRole('button',{name:'Save draft & add steps'}).click()
    await page.waitForURL(/\/studio\/simulations\/[a-f0-9-]{36}$/)
    const id=new URL(page.url()).pathname.split('/').at(-1)
    await page.getByRole('button',{name:VICI_PRACTICES[scenario].title,exact:true}).click()
    await page.getByText('Practice loaded.',{exact:false}).waitFor()
    await page.getByRole('button',{name:'Save steps',exact:true}).click()
    await page.getByText('All steps saved.',{exact:false}).waitFor()
    assert.equal(sql(`select scenario from public.training_vici_challenges where content_id='${id}'`),scenario)
    if(scenario==='dead_air'){
      await page.getByLabel('Call recording',{exact:true}).setInputFiles({name:'synthetic-silence.wav',mimeType:'audio/wav',buffer:Buffer.from(encodePcmWav(new Float32Array(22050)))})
      await page.getByLabel('End seconds',{exact:true}).fill('1')
      await page.getByLabel('I have permission to use this clip and have removed personal data.',{exact:true}).check()
      await page.getByRole('button',{name:'Attach private clip',exact:true}).click()
      await page.getByText('Private clip attached.',{exact:true}).waitFor()
      assert.equal(sql(`select count(*) from public.training_vici_audio where content_id='${id}'`),'1')
    }
    await page.getByRole('button',{name:'Review & publish →'}).click()
    await page.getByRole('button',{name:'Confirm publish',exact:true}).click()
    await page.getByRole('button',{name:'Edit update',exact:true}).waitFor()
    return id
  }
  const callbackId=await create('callback','34000000-0000-4000-8000-000000000016')
  pass('Studio has fixed Opener learners, creates canonical manual mission and validates private source screens')
  await page.goto(app+'/academy/simulations')
  await page.getByRole('heading',{name:'Vici Simulator',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:/Continue|Confirm entry|Confirm selection|Show hint/}).count(),0)
  assert.equal(await page.getByRole('button',{name:'CB - Callbacks',exact:true}).count(),0)
  await responsive('vici-staff-paused')
  await page.getByRole('button',{name:'YOU ARE PAUSED',exact:true}).click()
  await page.getByRole('region',{name:'Pause codes panel',exact:true}).waitFor()
  assert.equal(await page.locator('.vici-pause-menu').count(),0)
  assert.equal(await page.locator('.vici-pause-columns > div').count(),2)
  await responsive('vici-full-pause-codes')
  await page.getByRole('button',{name:'RESUME DIALING',exact:true}).click()
  await page.getByRole('button',{name:'YOU ARE ACTIVE',exact:true}).click()
  for(const name of ['Break - Break','Manage - Talking with Manager','RR - Restroom','Tech - Tech or System Issues','Lunch - Lunch']) {
    await page.getByRole('button',{name,exact:true}).click()
    await page.getByRole('button',{name:'YOU ARE PAUSED',exact:true}).click()
  }
  await page.getByRole('button',{name:'CB - Callbacks',exact:true}).click()
  assert.ok(await page.getByRole('region',{name:'Action history',exact:true}).locator('li').count()>=14)
  assert.equal(await page.locator('.vici-action-result--incorrect').count(),0)
  await page.getByRole('button',{name:'VICIdial logo',exact:true}).click()
  await page.getByRole('button',{name:'MANUAL DIAL',exact:true}).click()
  await page.getByLabel('Phone Number',{exact:true}).fill('2025550147')
  await responsive('vici-staff-manual')
  await page.getByRole('button',{name:'Dial Now',exact:true}).click()
  await page.getByText('LIVE CALL',{exact:true}).waitFor()
  await page.getByRole('button',{name:'HANGUP CUSTOMER',exact:true}).click()
  await page.getByText('CALL DISPOSITION',{exact:true}).waitFor()
  await responsive('vici-staff-disposition')
  await page.getByRole('button',{name:'NI - Not Interested',exact:true}).click()
  await page.getByRole('button',{name:'SUBMIT',exact:true}).click()
  await page.getByRole('button',{name:'YOU ARE ACTIVE',exact:true}).waitFor()
  assert.equal(await page.locator('.vici-action-result--correct').count(),8)
  await responsive('vici-numbered-actions')
  assert.equal(sql('select count(*) from public.training_attempts'),'0')
  pass('Staff manual call, green disposition and Submit resume dialing with no hints or learner records')

  for (const scenario of ['login','dead_air','answering','mailbox_full','english','spxfer','mock']) {
    await page.goto(app+'/academy/simulations/preview/'+scenario)
    await page.getByRole('heading',{name:'Vici Simulator',exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:/Sounds on|Sounds off/}).count(),0)
    if (scenario==='login') {
      await responsive('vici-login-welcome')
      await page.getByRole('button',{name:'Agent Login',exact:true}).click()
      await page.getByLabel('Phone Password',{exact:true}).fill('TRAINING')
      await responsive('vici-phone-login')
      await page.getByRole('button',{name:'SUBMIT',exact:true}).click()
      await page.getByLabel('User Password',{exact:true}).fill('TRAINING')
      await page.getByLabel('Campaign',{exact:true}).selectOption('OPENERS2')
      await responsive('vici-campaign-login')
      await page.getByRole('button',{name:'SUBMIT',exact:true}).click()
      await page.getByRole('button',{name:'YOU ARE PAUSED',exact:true}).click()
      await page.getByRole('button',{name:'RESUME DIALING',exact:true}).click()
    } else {
      if(scenario==='mock') {
        for(let i=0;i<4;i++) await page.getByRole('button',{name:'New customer',exact:true}).click()
        assert.equal(await page.getByLabel('Loan Monthly Cost',{exact:true}).inputValue(),'')
        assert.equal(await page.getByLabel('Phone',{exact:true}).inputValue(),'2025550151')
        await page.getByRole('button',{name:'5',exact:true}).click()
        assert.equal(await page.getByLabel('Webphone number',{exact:true}).inputValue(),'5')
        await responsive('vici-customer-bank-webphone')
      }
      if(['english','spxfer'].includes(scenario)){
        await page.getByRole('button',{name:'TRANSFER - CONF',exact:true}).click()
        if(scenario==='spxfer'){
          await page.getByRole('button',{name:'PRESETS',exact:true}).click()
          await page.getByLabel('Language',{exact:true}).selectOption('Spanish')
        }
        await page.getByRole('button',{name:'DIAL WITH CUSTOMER',exact:true}).click()
        await page.getByRole('button',{name:'LEAVE 3-WAY CALL',exact:true}).click()
        await page.getByText('Action not completed.',{exact:true}).waitFor()
        await page.waitForFunction(()=>document.querySelector('.vici-advisor')?.textContent.includes('15 / 15 seconds'))
        await page.getByRole('button',{name:'LEAVE 3-WAY CALL',exact:true}).click()
      }else await page.getByRole('button',{name:'HANGUP CUSTOMER',exact:true}).click()
      const dispo=scenario==='dead_air'?'DAIR - Dead Air':scenario==='english'?'XFER - Call Transferred':scenario==='spxfer'?'SPXFER - Spanish Xfer':scenario==='mock'?'NI - Not Interested':'A - Answering Machine'
      await page.getByRole('button',{name:dispo,exact:true}).click()
      await page.getByRole('button',{name:'SUBMIT',exact:true}).click()
    }
    await page.getByRole('button',{name:'YOU ARE ACTIVE',exact:true}).waitFor()
    pass('Staff practice '+scenario+' completes manually; no learner writes')
  }
  assert.equal(sql('select count(*) from public.training_attempts'),'0')
  await page.goto(app+'/studio/simulations/'+callbackId)
  await page.getByRole('button',{name:'Edit update',exact:true}).click()
  await page.waitForURL(url=>!url.pathname.includes(callbackId))
  const revision=new URL(page.url()).pathname.split('/').at(-1)
  assert.equal(sql(`select scenario from public.training_vici_challenges where content_id='${revision}'`),'callback')
  pass('published revision clones challenge and private screens while retaining original version')
  const asiaId=await create('asia','34000000-0000-4000-8000-000000000011')
  const agentContext=await context(), agentPage=await agentContext.newPage()
  agentPage.setDefaultTimeout(15000); agentPage.on('pageerror',e=>errors.push(e.message))
  await agentPage.goto(app+'/agent/signin')
  await agentPage.getByLabel('Agent ID',{exact:true}).fill('992611')
  await agentPage.getByLabel('PIN',{exact:true}).fill(agentPin)
  await agentPage.getByRole('button',{name:'Continue',exact:true}).click(); await agentPage.waitForURL('**/go')
  await agentPage.goto(app+'/academy/simulations')
  await agentPage.getByRole('button',{name:'Let Pulse choose →',exact:true}).click()
  await agentPage.getByRole('button',{name:'TRANSFER - CONF',exact:true}).waitFor()
  const attempt=new URL(agentPage.url()).searchParams.get('attempt')
  assert.equal(new URL(agentPage.url()).pathname,'/academy/simulations/'+asiaId)
  assert.equal(await agentPage.getByRole('button',{name:/Confirm selection|I understand/}).count(),0)
  assert.equal(await agentPage.getByRole('button',{name:'Show hint',exact:true}).count(),0)
  await agentPage.getByRole('button',{name:'TRANSFER - CONF',exact:true}).click()
  await agentPage.getByRole('button',{name:'PRESETS',exact:true}).click()
  await agentPage.getByLabel('Language',{exact:true}).selectOption('Spanish')
  await agentPage.locator('.vici-presets').getByRole('button',{name:'LOCAL CLOSER',exact:true}).click()
  await agentPage.getByLabel('Disposition',{exact:true}).selectOption('SPXFER')
  await agentPage.getByText('Action not completed.',{exact:true}).waitFor()
  assert.equal(await agentPage.locator('.vici-action-result--incorrect').count(),1)
  assert.equal(await agentPage.locator('.vici-action-result--correct').count(),4)
  assert.equal(await agentPage.getByRole('heading',{name:'Vici Simulator',exact:true}).count(),1)
  await agentPage.reload(); await agentPage.getByLabel('Disposition',{exact:true}).waitFor()
  assert.equal(new URL(agentPage.url()).searchParams.get('attempt'),attempt)
  for(const [width,height] of [[1440,1100],[820,1180],[390,844]]) {
    await agentPage.setViewportSize({width,height})
    await agentPage.screenshot({path:`review-evidence.local/sim-1/browser/vici-agent-asia-${width}.png`,fullPage:true})
    assert.ok(await agentPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Agent page overflow '+width)
  }
  await agentPage.getByLabel('Disposition',{exact:true}).selectOption('SPANISH SPEAKER')
  await agentPage.getByText('CALL DISPOSITION',{exact:true}).waitFor()
  assert.equal(sql(`select count(*) from public.training_results where attempt_id='${attempt}'`),'0')
  await agentPage.getByRole('button',{name:'SPANIS - Spanish Speaker',exact:true}).click()
  await agentPage.getByRole('button',{name:'SUBMIT',exact:true}).click()
  await agentPage.getByText('Practice complete · 95%',{exact:true}).waitFor()
  await agentPage.getByRole('button',{name:'YOU ARE ACTIVE',exact:true}).waitFor()
  assert.equal(await agentPage.locator('.vici-action-result--correct').count(),3)
  for(const name of ['Manage - Talking with Manager','RR - Restroom','Tech - Tech or System Issues']) {
    await agentPage.getByRole('button',{name:/YOU ARE ACTIVE|YOU ARE PAUSED/,exact:true}).click()
    await agentPage.getByRole('button',{name,exact:true}).click()
    await agentPage.getByRole('button',{name:'YOU ARE PAUSED',exact:true}).waitFor()
  }
  await agentPage.getByRole('button',{name:'YOU ARE PAUSED',exact:true}).click()
  await agentPage.getByRole('button',{name:'RESUME DIALING',exact:true}).click()
  await agentPage.getByRole('button',{name:'YOU ARE ACTIVE',exact:true}).waitFor()
  assert.equal(sql(`select score_percent::int from public.training_results where attempt_id='${attempt}'`),'95')
  assert.equal(sql(`select selection_mode from public.training_simulation_attempts where attempt_id='${attempt}'`),'assigned')
  pass('server-confirmed numbered actions, Asia SPXFER rejection and SPANIS wrap-up, six pause controls, authoritative immutable score and responsive layouts')
  await agentPage.getByRole('button',{name:'Practice again →'}).click()
  await agentPage.waitForURL(url=>url.searchParams.get('attempt')!==attempt)
  await agentPage.getByRole('button',{name:'TRANSFER - CONF',exact:true}).waitFor()
  assert.notEqual(new URL(agentPage.url()).searchParams.get('attempt'),attempt)
  assert.equal(sql(`select count(*) from public.training_results where attempt_id='${attempt}'`),'1')
  pass('manual mission replay preserves prior immutable learner results')
  const deadAirId=await create('dead_air','34000000-0000-4000-8000-000000000011')
  await agentPage.goto(app+'/academy/simulations/'+deadAirId)
  await agentPage.locator('audio').waitFor()
  const clipUrl=await agentPage.locator('audio').getAttribute('src')
  assert.ok(clipUrl.includes('/storage/v1/object/sign/training-media/'))
  // Read through the browser route so the signed URL reaches the owned
  // disposable storage transport, never the unrelated local default stack.
  assert.equal(await agentPage.evaluate(url=>fetch(url).then(response=>response.status),clipUrl),200)
  await agentPage.getByRole('button',{name:'HANGUP CUSTOMER',exact:true}).click()
  await agentPage.getByText('CALL DISPOSITION',{exact:true}).waitFor()
  await agentPage.locator('audio').waitFor({state:'detached'})
  assert.equal(await agentPage.locator('audio').count(),0)
  await agentPage.getByRole('button',{name:'A - Answering Machine',exact:true}).click()
  await agentPage.getByText('Action not completed.',{exact:true}).waitFor()
  await agentPage.getByRole('button',{name:'DAIR - Dead Air',exact:true}).click()
  await agentPage.getByRole('button',{name:'SUBMIT',exact:true}).click()
  await agentPage.getByText('Practice complete · 95%',{exact:true}).waitFor()
  pass('Studio trims synthetic clip to private WAV; Agent reads only own current call and grades Dead Air on server')
  await page.goto(app+'/academy')
  await page.getByRole('button',{name:'Vici Simulator →',exact:true}).waitFor()
  assert.equal(await page.locator('.ac-hero').count(),0)
  await responsive('academy-search-first')
  pass('Academy opens with search and Vici Simulator entry on desktop tablet and mobile')
}
