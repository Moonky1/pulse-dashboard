import assert from 'node:assert/strict'

export async function runViciBrowser({ page, context, app, sql, responsive, pass, agentPin, errors }) {
  const create = async (scenario,teamId) => {
    await page.goto(app+'/studio/simulations/create')
    assert.equal(await page.getByText('Positions · optional',{exact:true}).count(),0)
    await page.getByLabel('Title',{exact:true}).fill(scenario==='callback'?'Callback · manual dial':'Asia · Spanish-speaking customer')
    await page.getByLabel('Dialer practice',{exact:true}).check()
    await page.getByLabel('Audience',{exact:true}).selectOption('team')
    await page.getByLabel('Team',{exact:true}).selectOption(teamId)
    await page.getByRole('button',{name:'Save draft & add steps'}).click()
    await page.waitForURL(/\/studio\/simulations\/[a-f0-9-]{36}$/)
    const id=new URL(page.url()).pathname.split('/').at(-1)
    await page.getByRole('button',{name:scenario==='callback'?'Use Callback template':'Use Asia Spanish-routing template',exact:true}).click()
    await page.getByText('Synthetic screens uploaded privately.',{exact:false}).waitFor()
    await page.getByRole('button',{name:'Save steps',exact:true}).click()
    await page.getByText('All steps saved.',{exact:false}).waitFor()
    assert.equal(sql(`select scenario from public.training_vici_challenges where content_id='${id}'`),scenario)
    await page.getByRole('button',{name:'Review & publish →'}).click()
    await page.getByRole('button',{name:'Confirm publish',exact:true}).click()
    await page.getByRole('button',{name:'Edit update',exact:true}).waitFor()
    return id
  }
  const callbackId=await create('callback','34000000-0000-4000-8000-000000000016')
  pass('Studio has fixed Opener learners, creates canonical manual mission and validates private source screens')
  await page.goto(app+'/academy/simulations')
  await page.getByRole('heading',{name:'VICI Simulator',exact:true}).waitFor()
  await page.getByRole('link',{name:'Open dialer preview →'}).first().click()
  await page.getByRole('button',{name:'CB - Callbacks',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:/Continue|Confirm entry|Confirm selection/}).count(),0)
  await page.getByRole('button',{name:'Break - Break',exact:true}).click()
  await page.getByText('That action does not complete',{exact:false}).waitFor()
  await page.getByRole('button',{name:'Show hint',exact:true}).click()
  await page.getByText('Hint: Choose CB - Callbacks in the pause-code menu.',{exact:true}).waitFor()
  await responsive('vici-staff-paused')
  await page.getByRole('button',{name:'CB - Callbacks',exact:true}).click()
  await page.getByRole('button',{name:'VICIdial logo',exact:true}).click()
  await page.getByRole('button',{name:'MANUAL DIAL',exact:true}).click()
  await page.getByLabel('Phone Number',{exact:true}).fill('2025550147')
  await responsive('vici-staff-manual')
  await page.getByRole('button',{name:'Dial Now',exact:true}).click()
  await page.getByRole('heading',{name:'Reference workflow completed.',exact:true}).waitFor()
  assert.equal(sql('select count(*) from public.training_attempts'),'0')
  pass('Staff solves Callback with real manual controls and optional hints, without any learner attempts/results')
  await page.goto(app+'/studio/simulations/'+callbackId)
  await page.getByRole('button',{name:'Edit update',exact:true}).click()
  await page.waitForURL(url=>!url.pathname.includes(callbackId))
  const revision=new URL(page.url()).pathname.split('/').at(-1)
  assert.equal(sql(`select scenario from public.training_vici_challenges where content_id='${revision}'`),'callback')
  pass('published revision clones challenge and private screens while retaining original version')
  const asiaId=await create('asia','34000000-0000-4000-8000-000000000011')
  const agentContext=await context(), agentPage=await agentContext.newPage()
  agentPage.setDefaultTimeout(15000); agentPage.on('pageerror',e=>errors.push(e.message))
  await agentPage.goto(app+'/agent/signin')
  await agentPage.getByLabel('Agent ID',{exact:true}).fill('992611')
  await agentPage.getByLabel('PIN',{exact:true}).fill(agentPin)
  await agentPage.getByRole('button',{name:'Continue',exact:true}).click(); await agentPage.waitForURL('**/go')
  await agentPage.goto(app+'/academy/simulations')
  await agentPage.getByRole('button',{name:'Let Pulse choose →',exact:true}).click()
  await agentPage.getByRole('button',{name:'PRESETS',exact:true}).waitFor()
  const attempt=new URL(agentPage.url()).searchParams.get('attempt')
  assert.equal(new URL(agentPage.url()).pathname,'/academy/simulations/'+asiaId)
  assert.equal(await agentPage.getByRole('button',{name:/Confirm selection|I understand/}).count(),0)
  const goal=await agentPage.locator('.sim-player-title h1').innerText()
  await agentPage.getByRole('button',{name:'PRESETS',exact:true}).click()
  await agentPage.getByLabel('Language',{exact:true}).selectOption('Spanish')
  await agentPage.locator('.vici-presets').getByRole('button',{name:'LOCAL CLOSER',exact:true}).click()
  await agentPage.getByLabel('Disposition',{exact:true}).selectOption('SPXFER')
  await agentPage.getByText('That action does not complete',{exact:false}).waitFor()
  assert.equal(await agentPage.locator('.sim-player-title h1').innerText(),goal)
  await agentPage.reload(); await agentPage.getByLabel('Disposition',{exact:true}).waitFor()
  assert.equal(new URL(agentPage.url()).searchParams.get('attempt'),attempt)
  for(const [width,height] of [[1440,1100],[820,1180],[390,844]]) {
    await agentPage.setViewportSize({width,height})
    await agentPage.screenshot({path:`review-evidence.local/sim-1/browser/vici-agent-asia-${width}.png`,fullPage:true})
    assert.ok(await agentPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Agent page overflow '+width)
  }
  await agentPage.getByLabel('Disposition',{exact:true}).selectOption('SPANISH SPEAKER')
  await agentPage.getByRole('heading',{name:'You completed the workflow.',exact:true}).waitFor()
  assert.equal(sql(`select score_percent::int from public.training_results where attempt_id='${attempt}'`),'95')
  assert.equal(sql(`select selection_mode from public.training_simulation_attempts where attempt_id='${attempt}'`),'assigned')
  pass('server-assigned team-only Agent mission, manual Asia controls, SPXFER rejection, saved resume, authoritative score and responsive layouts')
  await agentPage.getByRole('button',{name:'Practice again →'}).click()
  await agentPage.getByRole('button',{name:'PRESETS',exact:true}).waitFor()
  assert.notEqual(new URL(agentPage.url()).searchParams.get('attempt'),attempt)
  assert.equal(sql(`select count(*) from public.training_results where attempt_id='${attempt}'`),'1')
  pass('manual mission replay preserves prior immutable learner results')
}
