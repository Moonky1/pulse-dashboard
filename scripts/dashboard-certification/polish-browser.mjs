import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
const root = process.env.PULSE_PLAYWRIGHT_ROOT || 'C:/Users/simon/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'
const { chromium } = createRequire(root+'/package.json')('playwright')
const server = await createServer({configFile:false,publicDir:false,plugins:[react()],server:{host:'127.0.0.1',port:53960,strictPort:true}})
await server.listen()
const browser = await chromium.launch({channel:'chrome',headless:true})
const context = await browser.newContext({viewport:{width:1440,height:1050},serviceWorkers:'block'})
const page = await context.newPage(), errors=[], external=[]
page.on('pageerror',e=>errors.push(e.message))
await context.route('**/*',route=>{if(new URL(route.request().url()).origin!=='http://127.0.0.1:53960'){external.push(route.request().url());return route.abort()}return route.continue()})
try {
  await mkdir('review-evidence.local/dashboard-polish',{recursive:true})
  await page.goto('http://127.0.0.1:53960/scripts/dashboard-certification/review.html?mode=populated&pet=1')
  await page.waitForFunction(()=>document.querySelector('.dash-metric strong')?.textContent==='40')
  assert.equal(await page.locator('.dash-metric strong').first().evaluate(e=>getComputedStyle(e).color),'rgb(245, 245, 250)')
  await page.locator('.dash-metric').first().hover()
  await page.waitForTimeout(260)
  assert.notEqual(await page.locator('.dash-metric').first().evaluate(e=>getComputedStyle(e).transform),'none')
  await page.getByRole('button',{name:'Agents40',exact:true}).click()
  const rail=page.getByRole('region',{name:'Scroll table horizontally'}), table=page.locator('.dash-top-table > .dash-table-scroll')
  assert.ok(await rail.isVisible())
  assert.ok((await rail.boundingBox()).y < (await table.boundingBox()).y)
  await rail.focus(); await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(300)
  assert.ok(await rail.evaluate(e=>e.scrollLeft)>0)
  assert.ok(Math.abs(await rail.evaluate(e=>e.scrollLeft)-await table.evaluate(e=>e.scrollLeft))<2)
  await table.evaluate(e=>{e.scrollLeft=0})
  await page.waitForTimeout(100)
  assert.equal(await rail.evaluate(e=>e.scrollLeft),0)
  await page.screenshot({path:'review-evidence.local/dashboard-polish/table-top.png'})
  await page.getByRole('button',{name:'Closers',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'Openers',exact:true}).getAttribute('aria-pressed'),'true')
  await page.locator('.pulse-pet--nope').waitFor()
  assert.ok(await page.getByText('Not available yet ✋',{exact:true}).isVisible())
  await page.waitForTimeout(400)
  await page.screenshot({path:'review-evidence.local/dashboard-polish/closers.png'})
  await page.locator('.pulse-pet--nope').waitFor({state:'detached'})
  assert.equal(await page.getByText('Not available yet ✋',{exact:true}).count(),0)
  await page.mouse.move(50,300)
  await page.waitForTimeout(450)
  assert.ok(parseFloat(await page.locator('.pulse-pet').evaluate(e=>e.style.getPropertyValue('--pet-eye-x'))) < -1)
  await page.waitForTimeout(2000)
  assert.ok(Math.abs(parseFloat(await page.locator('.pulse-pet').evaluate(e=>e.style.getPropertyValue('--pet-eye-x')))) < .2)
  assert.equal(await page.getByText('Source details',{exact:true}).count(),0)
  assert.equal(await page.getByText('Additional review rules',{exact:true}).count(),0)
  assert.equal(await page.getByText('Rules',{exact:true}).count(),1)
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button',{name:'Closers',exact:true}).focus()
  await page.keyboard.press('Enter')
  await page.locator('.pulse-pet--nope').waitFor()
  assert.equal(await page.locator('.pulse-pet__nope-hand').evaluate(e=>getComputedStyle(e).animationName),'none')
  await page.setViewportSize({width:390,height:844})
  assert.equal(await rail.isVisible(),false)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.setViewportSize({width:650,height:844})
  assert.ok(await table.isVisible())
  await page.goto('http://127.0.0.1:53960/scripts/dashboard-certification/review.html?mode=manual')
  await page.getByText('Saved reports',{exact:true}).waitFor()
  assert.deepEqual(errors,[]); assert.deepEqual(external,[])
  console.log('PASS top scrollbar sync, white metrics and hover, Closers feedback, pet gaze/idle, reduced motion, compact labels, mobile, no external requests')
} finally {await context.close();await browser.close();await server.close()}
